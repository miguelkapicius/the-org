        static char Base(char c)
        {
            c = char.ToUpperInvariant(c);
            switch (c)
            {
                case 'Á': case 'À': case 'Â': case 'Ã': return 'A';
                case 'É': case 'Ê': return 'E';
                case 'Í': return 'I';
                case 'Ó': case 'Ô': case 'Õ': return 'O';
                case 'Ú': return 'U';
                case 'Ç': return 'C';
                case '»': return '>';
            }
            return c;
        }

        public static int Width(string s) => s.Length * (GW + 1) - 1;

        /// <summary>Desenha o texto com sombra (contorno escuro) no quadro W x H.</summary>
        public static void Draw(C3[] buf, int W, int H, int x, int y, string s, C3 col, C3? shadow = null)
        {
            C3 sh = shadow ?? new C3(20, 14, 12);
            for (int pass = 0; pass < 2; pass++)
            {
                int cx = x;
                foreach (char ch in s)
                {
                    if (G.TryGetValue(Base(ch), out var g))
                        for (int r = 0; r < GH; r++)
                            for (int c = 0; c < GW; c++)
                            {
                                if (g[r][c] != '1') continue;
                                if (pass == 0)
                                {
                                    foreach (var (dx, dy) in new[] { (1, 0), (-1, 0), (0, 1), (0, -1), (1, 1) })
                                        Put(buf, W, H, cx + c + dx, y + r + dy, sh);
                                }
                                else Put(buf, W, H, cx + c, y + r, col);
                            }
                    cx += GW + 1;
                }
            }
        }

        static void Put(C3[] buf, int W, int H, int x, int y, C3 c)
        {
            if (x >= 0 && y >= 0 && x < W && y < H) buf[y * W + x] = c;
        }
    }
